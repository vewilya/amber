import json
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import torch
from torch import nn

from torchline.export_header import c_array

def rms(s):
    return torch.sqrt(torch.mean(s**2))


def lin2dB(s):
    return 20 * torch.log10(torch.abs(s))


def dB2lin(s):
    return 10 ** (s / 20)


def generate(model: nn.Module):
    print("--- Generate Lookup Table ---")

    s = dB2lin(-12) * torch.sin(2 * math.pi * torch.arange(4800) / 48)  # -12 dBFS sine
    x = s.unsqueeze(1).repeat(1, 2)
    drive_min, drive_max, size = 0.1, 3.0, 64
    spacing = torch.linspace(drive_min, drive_max, size)

    table = []

    for drive in spacing:
        with torch.no_grad():
            y = model(drive * x)[:, 0]

        y = y - y.mean()  # strip DC
        makeup = rms(s) / rms(y)

        table.append(makeup.item())

    write_header(table, drive_min, drive_max)

    # with open("data/lookup_table.json", "w") as f:
    #     json.dump({drive.item(): makeup for drive, makeup in zip(spacing, table)}, f)


DSP_SRC = Path(__file__).resolve().parents[4] / "dsp" / "src"  # libs/dsp/src


def write_header(table, drive_min, drive_max, path=DSP_SRC / "amber_makeup.h"):
    with open(path, "w") as file:
        file.write("// Generated by `torchline lookup` -- do not edit by hand\n")
        file.write("#ifndef AMBER_MAKEUP_H\n")
        file.write("#define AMBER_MAKEUP_H\n\n")
        file.write(f"#define MAKEUP_TABLE_SIZE {len(table)}\n")
        file.write(f"#define MAKEUP_DRIVE_MIN {drive_min!r}f\n")
        file.write(f"#define MAKEUP_DRIVE_MAX {drive_max!r}f\n\n")
        file.write(
            f"static const float makeup_table[MAKEUP_TABLE_SIZE] = {c_array(table)};\n\n"
        )
        file.write("#endif // AMBER_MAKEUP_H\n")
